#!/usr/bin/env python3
"""
Generates desktop/src/main/kotlin/com/ars3nb/volta/desktop/i18n/AndroidMatched.kt.

Volta for Windows keeps its typed word list (Strings.kt, one Lang*.kt per language).
Wherever a Russian text there is word for word one of the Android app's (values-ru),
the Windows app shows the Android translation of that key in every language, so both
apps say the same thing. A text with no Android twin may be translated in
desktop/src/main/res/values-*/strings_desktop.xml under the name d_<property>; otherwise
the language's own Lang*.kt (or English) is used.

Run from the repository root after changing Strings.kt or LangRu.kt:
    python3 tools/desktop_strings.py
"""
import re, glob, os, sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
I18N = f'{ROOT}/desktop/src/main/kotlin/com/ars3nb/volta/desktop/i18n'


def unescape(raw):
    out, quoted, space, i = [], False, False, 0
    while i < len(raw):
        c = raw[i]
        if c == '\\' and i + 1 < len(raw):
            if space: out.append(' '); space = False
            n = raw[i + 1]
            out.append({'n': '\n', 't': '\t'}.get(n, n))
            i += 2
            continue
        if c == '"': quoted = not quoted
        elif not quoted and c.isspace(): space = bool(out)
        else:
            if space: out.append(' '); space = False
            out.append(c)
        i += 1
    return ''.join(out)


def load(folder):
    m = {}
    for f in sorted(glob.glob(f'{ROOT}/app/src/main/res/{folder}/strings*.xml')):
        for e in ET.parse(f).getroot():
            if e.tag == 'string' and e.get('translatable') != 'false':
                m.setdefault(e.get('name'), unescape(''.join(e.itertext())))
    return m


def kotlin_unescape(s):
    return s.encode('latin-1', 'backslashreplace').decode('unicode_escape') if '\\u' in s else \
        s.replace('\\n', '\n').replace('\\"', '"').replace('\\$', '$').replace('\\\\', '\\')


ru = load('values-ru')
by_text = {}
for k, v in ru.items():
    by_text.setdefault(v, k)

iface = open(f'{I18N}/Strings.kt').read()
props = re.findall(r'^\s*val (\w+): (String|\(([^)]*)\) -> String)\s*$', iface, re.M)
src = open(f'{I18N}/LangRu.kt').read()

# override val x: String = "...", possibly "..." + "..." over several lines
simple = {}
for m in re.finditer(r'override val (\w+): String =\s*((?:"(?:[^"\\]|\\.)*"\s*(?:\+\s*)?)+)', src):
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))
    simple[m.group(1)] = kotlin_unescape(''.join(parts))

# override val x: (A, B) -> String = { a, b -> "...$a...${b}..." }  or { "...$it..." }
lambdas = {}
for m in re.finditer(r'override val (\w+): \(([^)]*)\) -> String = \{\s*(?:(\w+(?:\s*,\s*\w+)*)\s*->\s*)?"((?:[^"\\]|\\.)*)"\s*\}', src):
    name, types, params, body = m.groups()
    params = [p.strip() for p in (params or 'it').split(',')]
    tys = [t.strip() for t in types.split(',')]
    android = kotlin_unescape(body).replace('%', '%%')
    ok = True
    for i, p in enumerate(params):
        spec = 'd' if tys[i] in ('Int', 'Long') else 's'
        android, n = re.subn(r'\$\{' + p + r'\}|\$' + p + r'\b', f'%{i + 1}${spec}', android)
        if n == 0: ok = False
    if ok and '$' not in android.replace('%1$', '').replace('%2$', '').replace('%3$', ''):
        lambdas[name] = android

out = []
w = out.append
w('// Generated by tools/desktop_strings.py from Strings.kt, LangRu.kt and the Android')
w('// app\'s values-ru. Do not edit: change those and run the script again.')
w('package com.ars3nb.volta.desktop.i18n')
w('')
w('/**')
w(' * A language\'s words: the Android app\'s translation wherever the Russian text is the')
w(' * same as one of the Android app\'s, then a desktop translation (d_<name> in')
w(' * desktop/src/main/res), then [base].')
w(' */')
w('@Suppress("RedundantSuppression", "LongMethod")')
w('open class AndroidMatched(private val tag: String, private val base: Strings) : Strings by base {')
w('    private fun pick(key: String?, own: String, fallback: String): String {')
w('        val t = Res.table(tag).strings')
w('        return (key?.let { t[it] } ?: t["d_$own"]) ?: fallback')
w('    }')
w('')
w('    private fun fmt(key: String?, own: String, vararg args: Any): String? {')
w('        val t = Res.table(tag).strings')
w('        val pattern = key?.let { t[it] } ?: t["d_$own"] ?: return null')
w('        return runCatching { String.format(java.util.Locale.forLanguageTag(tag), pattern, *args) }.getOrNull()')
w('    }')
w('')
matched = 0
for name, typ, args in props:
    if typ == 'String':
        key = by_text.get(simple.get(name))
        if key: matched += 1
        k = f'"{key}"' if key else 'null'
        w(f'    override val {name}: String get() = pick({k}, "{name}", base.{name})')
    else:
        tys = [t.strip() for t in args.split(',')]
        key = by_text.get(lambdas.get(name))
        if key: matched += 1
        k = f'"{key}"' if key else 'null'
        ps = ', '.join(f'a{i}: {t}' for i, t in enumerate(tys))
        ns = ', '.join(f'a{i}' for i in range(len(tys)))
        w(f'    override val {name}: ({", ".join(tys)}) -> String get() = {{ {ps} -> fmt({k}, "{name}", {ns}) ?: base.{name}({ns}) }}')
w('}')
w('')
open(f'{I18N}/AndroidMatched.kt', 'w').write('\n'.join(out))
print(f'{len(props)} strings, {matched} matched to Android keys', file=sys.stderr)
