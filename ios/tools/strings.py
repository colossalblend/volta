#!/usr/bin/env python3
"""Volta for iOS: the translation table and the Localizable.strings files made from it.

    python3 ios/tools/strings.py           writes ios/Localization/<lang>.lproj/Localizable.strings
    python3 ios/tools/strings.py --check   fails when a key used in Swift is missing, a
                                           language lacks a key, or the %-placeholders of a
                                           translation differ from the Russian text

Russian is the source language. Keys used in Swift: L("key"), L10n.tr("key"),
L10n.plural("key", n) (needs key.one / key.other, plus key.few / key.many for ru and uk).
The table itself lives in strings_table.py next to this file.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
IOS = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from strings_table import LANGS, TABLE  # noqa: E402

KEY_USE = re.compile(r'(?:L10n\.tr|L10n\.plural|\bL)\(\s*"([A-Za-z0-9_.]+)"')
PLURAL_USE = re.compile(r'L10n\.plural\(\s*"([A-Za-z0-9_.]+)"')
PLACEHOLDER = re.compile(r"%(?:\d+\$)?[-+ 0#]*\d*(?:\.\d+)?(?:ll|l|h)?[@dDuUxXoOfeEgGcCsSpaAF]")
PLURAL_FORMS = {"ru": ["one", "few", "many"], "uk": ["one", "few", "many"]}


def swift_files():
    for root, dirs, files in os.walk(IOS):
        dirs[:] = [d for d in dirs if d not in (".build", "build", "Frameworks", "Volta.xcodeproj", "tools")]
        for f in files:
            if f.endswith(".swift"):
                yield os.path.join(root, f)


def used_keys():
    keys, plurals = set(), set()
    for path in swift_files():
        text = open(path, encoding="utf-8").read()
        for k in KEY_USE.findall(text):
            if "." in k:
                keys.add(k)
        plurals.update(PLURAL_USE.findall(text))
    return keys - plurals, plurals


def placeholders(s):
    return sorted(PLACEHOLDER.findall(s.replace("%%", "")))


def check():
    problems = []
    keys, plurals = used_keys()
    for k in sorted(keys):
        if k not in TABLE:
            problems.append(f"missing key: {k}")
    for k in sorted(plurals):
        for lang in LANGS:
            forms = ["other"] + PLURAL_FORMS.get(lang, ["one"])
            for form in forms:
                entry = TABLE.get(f"{k}.{form}")
                if entry is None or lang not in entry:
                    problems.append(f"missing plural {k}.{form} [{lang}]")
    for k, entry in sorted(TABLE.items()):
        if "ru" not in entry:
            problems.append(f"{k}: no Russian text")
            continue
        base = placeholders(entry["ru"])
        for lang in LANGS:
            if lang not in entry:
                if not re.search(r"\.(few|many)$", k):
                    problems.append(f"{k}: no {lang}")
                continue
            if placeholders(entry[lang]) != base:
                problems.append(f"{k} [{lang}]: placeholders {placeholders(entry[lang])} != {base}")
    unused = sorted(k for k in TABLE if k not in keys and not any(k.startswith(p + ".") for p in plurals))
    for k in unused:
        print(f"note: unused key {k}")
    if problems:
        for p in problems:
            print("::error::" + p if os.environ.get("GITHUB_ACTIONS") else p)
        print(f"{len(problems)} problem(s)")
        return 1
    print(f"ok: {len(keys)} keys and {len(plurals)} plurals in {len(LANGS)} languages")
    return 0


def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write():
    for lang in LANGS:
        folder = os.path.join(IOS, "Localization", f"{lang}.lproj")
        os.makedirs(folder, exist_ok=True)
        lines = ["/* Generated by ios/tools/strings.py from strings_table.py. Do not edit by hand. */", ""]
        for k in sorted(TABLE):
            entry = TABLE[k]
            text = entry.get(lang) or entry.get("en") or entry["ru"]
            lines.append(f'"{escape(k)}" = "{escape(text)}";')
        with open(os.path.join(folder, "Localizable.strings"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    print(f"wrote {len(TABLE)} keys for {', '.join(LANGS)}")


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check())
    write()
    sys.exit(check())
